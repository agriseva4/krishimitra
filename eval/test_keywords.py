W = ["वातावरण कसं राहील", "तापमान किती", "उद्या पावसाची शक्यता आहे का", "आज पाऊस पडेल का", "hawaman kasa ahe"]
M = ["टोमॅटोचे रेट", "आज बाजारात भाव काय", "आवक किती आहे", "कांद्याचा दर किती", "आज बाजारभाव सांगा"]
D = ["फळ सडतंय", "पाने गुंडाळतात", "पीक करपलं", "युरिया किती टाकू", "पानांवर मावा आलाय", "पाने पिवळी पडतायत", "अळी खातेय"]

fails = 0
def bad(msg):
    global fails; fails += 1; print("❌", msg)

n = 0
for crop, qs in CROPS.items():
    for q in qs:
        n += 1
        got = ai._detect_crops(q.lower(), [])
        if crop not in got: bad(f"पीक चुकलं: '{q}' -> {got} (अपेक्षित {crop})")
print(f"1) पीक ओळख: {n - fails}/{n}")

f1 = fails
for q in NO_CROP:
    got = ai._detect_crops(q.lower(), [])
    if got: bad(f"चुकीचं पीक पकडलं: '{q}' -> {got}")
print(f"2) चुकीचं पीक नाही: {len(NO_CROP) - (fails - f1)}/{len(NO_CROP)}")

f2 = fails
for q in W:
    if not mh.any_kw(mh.WEATHER_WORDS, q.lower()): bad(f"हवामान शब्द नाही जुळला: '{q}'")
for q in M:
    if not mh.any_kw(mh.MANDI_WORDS, q.lower()): bad(f"भाव शब्द नाही जुळला: '{q}'")
for q in D:
    if not (mh.any_kw(ai.DISEASE_WORDS, q.lower()) or mh.any_kw(ai.FERTILIZER_WORDS, q.lower())):
        bad(f"रोग/खत शब्द नाही जुळला: '{q}'")
total = len(W) + len(M) + len(D)
print(f"3) हवामान/भाव/रोग/खत: {total - (fails - f2)}/{total}")

print("\n✅ सगळं बरोबर" if not fails else f"\n⚠️ {fails} चुका वर दिसत आहेत")
sys.exit(1 if fails else 0)
